import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: "new", args: ["--no-sandbox","--disable-gpu"] });
const p = await b.newPage();
const errs = [];
p.on("pageerror", e => errs.push("pageerror: " + e.message));
p.on("console", m => { if (m.type() === "error") errs.push("console: " + m.text()); });
await p.goto("https://synapse-shift.hcode016.workers.dev/?v=2#staffshift", { waitUntil: "networkidle2", timeout: 60000 });
await p.waitForFunction(() => [...document.querySelectorAll("button")].some(x => (x.textContent||"").includes("مدیر پرستاری")), { timeout: 30000 });
await p.evaluate(() => [...document.querySelectorAll("button")].find(x => (x.textContent||"").includes("مدیر پرستاری")).click());
await p.waitForSelector("input[type=password]", { timeout: 20000 });
await p.type("input[type=password]", "0000");
await p.keyboard.press("Enter");
await p.waitForFunction(() => [...document.querySelectorAll("button")].some(x => (x.textContent||"").includes("برنامه‌ی شیفت")), { timeout: 30000 });
errs.length = 0;
await p.evaluate(() => [...document.querySelectorAll("button")].find(x => (x.textContent||"").includes("برنامه‌ی شیفت")).click());
await new Promise(r => setTimeout(r, 2500));
const state = await p.evaluate(() => ({ tab: (document.querySelector(".ss-view-tab.active")||{}).textContent || "", hasGrid: !!document.querySelector(".ss-grid"), title: (document.querySelector("h3")||{}).textContent || "" }));
console.log("STATE:", JSON.stringify(state));
console.log("ERRORS:", JSON.stringify(errs.slice(0,4), null, 1));
await b.close();
